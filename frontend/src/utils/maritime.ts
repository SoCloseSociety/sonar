/**
 * Get detailed vessel type info from AIS type code.
 * Handles range types (70-79 = Cargo, 80-89 = Tanker, 60-69 = Passenger).
 */
export function getVesselTypeInfo(typeCode: number | undefined | null): { name: string; emoji: string; category: string } {
  if (typeCode == null) return { name: 'Unknown', emoji: '❓', category: 'other' };
  if (VESSEL_TYPE_INFO[typeCode]) return VESSEL_TYPE_INFO[typeCode];
  // Range fallback
  if (typeCode >= 70 && typeCode < 80) return VESSEL_TYPE_INFO[70];
  if (typeCode >= 80 && typeCode < 90) return VESSEL_TYPE_INFO[80];
  if (typeCode >= 60 && typeCode < 70) return VESSEL_TYPE_INFO[60];
  if (typeCode >= 40 && typeCode < 50) return VESSEL_TYPE_INFO[40];
  return { name: `Type ${typeCode}`, emoji: '🚢', category: 'other' };
}

