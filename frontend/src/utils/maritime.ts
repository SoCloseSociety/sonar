/**
 * Get country from MMSI Maritime Identification Digits (first 3 digits).
 */
export function getCountryFromMMSI(mmsi: string): { code: string; name: string } | null {
  if (!mmsi || mmsi.length < 3) return null;
  const mid = mmsi.slice(0, 3);
  return MMSI_COUNTRY[mid] || null;
}

/**
 * ISO country code → flag emoji.
 */
export function countryFlag(code: string): string {
  if (!code || code.length < 2) return '';
  const c = code.toUpperCase();
  return String.fromCodePoint(
    0x1F1E6 + c.charCodeAt(0) - 65,
    0x1F1E6 + c.charCodeAt(1) - 65,
  );
}

/**
 * Get category color for vessel type.
 */
export function getVesselCategoryColor(category: string): string {
  switch (category) {
    case 'military': return '#ef4444';
    case 'cargo': return '#3b82f6';
    case 'tanker': return '#f97316';
    case 'passenger': return '#22d3ee';
    case 'fishing': return '#10b981';
    case 'service': return '#8b5cf6';
    default: return '#64748b';
  }
}
